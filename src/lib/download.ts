export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}

const GREEN: [number, number, number] = [42, 102, 77];

async function newDoc() {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  return doc;
}

type Doc = Awaited<ReturnType<typeof newDoc>>;

function header(doc: Doc, title: string, sub: string) {
  doc.setFillColor(...GREEN);
  doc.rect(0, 0, 595, 74, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.text('Smart AgriConnect', 40, 36);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.text(title, 40, 56);
  doc.setTextColor(30, 30, 30);
  doc.setFontSize(10);
  doc.setTextColor(90, 90, 90);
  doc.text(sub, 555, 56, { align: 'right' });
  doc.setTextColor(30, 30, 30);
}

function footer(doc: Doc, note: string) {
  doc.setFontSize(8.5);
  doc.setTextColor(120, 120, 120);
  doc.text(doc.splitTextToSize(note, 515), 40, 800);
}

function section(doc: Doc, y: number, label: string) {
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(...GREEN);
  doc.text(label, 40, y);
  doc.setDrawColor(...GREEN);
  doc.line(40, y + 5, 555, y + 5);
  doc.setTextColor(30, 30, 30);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  return y + 24;
}

function lines(doc: Doc, y: number, items: string[], bullet = true) {
  doc.setFontSize(11);
  for (const t of items) {
    const wrapped = doc.splitTextToSize(bullet ? `-  ${t}` : t, 505);
    if (y + wrapped.length * 14 > 780) {
      doc.addPage();
      y = 50;
    }
    doc.text(wrapped, 48, y);
    y += wrapped.length * 14 + 4;
  }
  return y;
}

export async function downloadScanReport(scan: Scan) {
  const d = getDisease(scan.diseaseId);
  const doc = await newDoc();
  header(doc, 'Crop Scan Report', new Date(scan.createdAt).toLocaleString('en-IN'));
  try {
    const data = scan.image.startsWith('data:') ? scan.image : await urlToDataUrl(scan.image);
    doc.addImage(data, 'JPEG', 40, 96, 190, 160);
  } catch {
    /* image optional */
  }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(60, 160, 80);
  doc.text('Detected disease', 250, 112);
  doc.setTextColor(30, 30, 30);
  doc.setFontSize(22);
  doc.text(d.name, 250, 140);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.text(`Severity: ${severityLabel(scan.score)} (${scan.score.toFixed(1)}/10)`, 250, 166);
  doc.text(`Crop: ${d.crop[0].toUpperCase()}${d.crop.slice(1)}`, 250, 184);
  doc.text(`Image: ${scan.fileName}`, 250, 202);
  doc.setTextColor(180, 40, 40);
  doc.text('This disease can reduce yield if not controlled.', 250, 226);
  doc.setTextColor(30, 30, 30);

  let y = section(doc, 284, 'Confidence breakdown');
  for (const c of scan.conf) {
    doc.text(`${c.name}`, 48, y);
    doc.setFillColor(225, 240, 228);
    doc.rect(200, y - 9, 260, 10, 'F');
    doc.setFillColor(54, 199, 90);
    doc.rect(200, y - 9, (260 * c.pct) / 100, 10, 'F');
    doc.text(`${c.pct}%`, 470, y);
    y += 22;
  }
  y = section(doc, y + 12, 'Overview');
  y = lines(doc, y, d.overview.split('\n'), false);
  y = section(doc, y + 12, 'Remedies - organic');
  y = lines(doc, y, d.remedies.organic);
  y = section(doc, y + 8, 'Remedies - physical');
  y = lines(doc, y, d.remedies.physical);
  y = section(doc, y + 8, 'Remedies - chemical');
  y = lines(doc, y, d.remedies.chemical);
  y = section(doc, y + 8, 'Prevention');
  lines(doc, y, d.prevention);
  footer(doc, 'DEMO REPORT: generated by a simulated scan using sample data. It is not a real diagnosis. Please consult your local agriculture officer before treating your crop.');
  doc.save(`scan-report-${d.id}.pdf`);
}

function orderTable(doc: Doc, o: Order, y: number) {
  doc.setFillColor(244, 233, 213);
  doc.rect(40, y, 515, 24, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.text('Item', 48, y + 16);
  doc.text('Qty', 320, y + 16);
  doc.text('Rate', 400, y + 16);
  doc.text('Amount', 548, y + 16, { align: 'right' });
  doc.setFont('helvetica', 'normal');
  y += 44;
  doc.text(o.name, 48, y);
  doc.text(`${o.qty} kg`, 320, y);
  doc.text(`Rs ${o.unitPrice}/kg`, 400, y);
  doc.text(`Rs ${o.total.toLocaleString('en-IN')}`, 548, y, { align: 'right' });
  y += 28;
  doc.line(40, y - 14, 555, y - 14);
  doc.setFont('helvetica', 'bold');
  doc.text('Total', 400, y + 4);
  doc.text(`Rs ${o.total.toLocaleString('en-IN')}`, 548, y + 4, { align: 'right' });
  doc.setFont('helvetica', 'normal');
  return y + 30;
}

export async function downloadInvoice(o: Order) {
  const doc = await newDoc();
  header(doc, 'Invoice (demo)', `Invoice INV-${o.id}`);
  let y = section(doc, 110, 'Bill details');
  doc.text(`Order: #${o.id}`, 48, y);
  doc.text(`Date: ${fmtDate(o.createdAt)}`, 320, y);
  y += 18;
  doc.text(`Buyer: Ramesh (Farmer)`, 48, y);
  doc.text(`Deliver to: ${o.address}`, 320, y);
  y += 18;
  doc.text(`Seller: ${o.seller}, ${o.sellerLocation}`, 48, y);
  y += 38;
  y = orderTable(doc, o, y);
  y = section(doc, y + 10, 'Payment');
  doc.text('Payment mode: Cash on delivery (demo)', 48, y);
  footer(doc, 'DEMO INVOICE: this document is generated by a frontend prototype with sample data. It is not a tax invoice and has no legal value.');
  doc.save(`invoice-${o.id}.pdf`);
}

export async function downloadTrackingSummary(o: Order) {
  const doc = await newDoc();
  const t = currentStep(o);
  header(doc, 'Order Tracking Summary', `Order #${o.id}`);
  let y = section(doc, 110, 'Order');
  doc.text(`${o.name}`, 48, y);
  y += 18;
  doc.text(`Quantity: ${o.qty} kg    Rate: Rs ${o.unitPrice}/kg    Total: Rs ${o.total.toLocaleString('en-IN')}`, 48, y);
  y += 18;
  doc.text(`Seller: ${o.seller}, ${o.sellerLocation}    Phone: ${o.phone}`, 48, y);
  y += 18;
  doc.text(`Estimated delivery: ${fmtDate(o.estDelivery)}`, 48, y);
  y = section(doc, y + 34, 'Shipment tracking');
  TIMELINE.forEach((label, i) => {
    const done = i <= t;
    doc.setFont('helvetica', done ? 'bold' : 'normal');
    doc.text(`${done ? '[x]' : '[ ]'}  ${label}`, 48, y);
    doc.setFont('helvetica', 'normal');
    doc.text(done ? fmtDateTime(stepTime(o, i)) : 'Pending', 300, y);
    y += 20;
  });
  footer(doc, 'DEMO DATA: tracking updates are simulated by this prototype and do not reflect a real shipment.');
  doc.save(`order-${o.id}-tracking.pdf`);
}
